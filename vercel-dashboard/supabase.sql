create table if not exists public.leads (
  id uuid primary key default gen_random_uuid(), first_name text not null default '', last_name text not null default '', company text not null default '', role text not null default '', email text not null default '', phone text not null default '', source text not null, consent_status text not null default 'unknown', do_not_contact boolean not null default false, created_at timestamptz not null default now()
);
create table if not exists public.audit_events (
  id bigint generated by default as identity primary key, event_type text not null, detail text not null default '', created_at timestamptz not null default now()
);
alter table public.leads enable row level security;
alter table public.audit_events enable row level security;
create policy "authenticated users can read leads" on public.leads for select to authenticated using (true);
create policy "authenticated users can manage leads" on public.leads for all to authenticated using (true) with check (true);
create policy "authenticated users can read events" on public.audit_events for select to authenticated using (true);
create policy "authenticated users can create events" on public.audit_events for insert to authenticated with check (true);
